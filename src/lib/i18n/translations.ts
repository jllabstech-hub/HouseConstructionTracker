export function getStageLocalized(
  stageName: string,
  lang: Language = "en",
  short: boolean = false
): string {
  const match = STAGE_TRANSLATIONS[stageName];
  if (!match) return stageName;
  if (lang === "te") {
    return short ? match.teShort : match.te;
  }
  return short ? match.enShort : match.en;
}
